-- Limpieza previa: permite volver a ejecutar el script sin errores.
BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('LOTES_ABONO', 'MONITOREO_PILAS', 'RECOLECCIONES',
                                  'PILAS_COMPOST', 'PROVEEDORES', 'USUARIOS', 'ROLES')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. ROLES: perfiles de acceso al sistema
--    codigo = identificador interno fijo (lo usan los permisos del backend)
--    nombre = texto visible que el administrador puede editar
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id_rol        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo        VARCHAR2(30)  NOT NULL,
  nombre        VARCHAR2(50)  NOT NULL,
  descripcion   VARCHAR2(200),
  CONSTRAINT pk_roles PRIMARY KEY (id_rol)
);

-- ---------------------------------------------------------------------
-- 2. USUARIOS: personas que ingresan al sistema
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
  id_usuario       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre           VARCHAR2(100) NOT NULL,
  correo           VARCHAR2(120) NOT NULL,
  contrasena_hash  VARCHAR2(100) NOT NULL,
  telefono         VARCHAR2(20),
  id_rol           NUMBER        NOT NULL,
  activo           CHAR(1)       DEFAULT 'S' NOT NULL,
  fecha_creacion   DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario)
);

-- ---------------------------------------------------------------------
-- 3. PROVEEDORES: puntos de recolección (plazas, fincas, agroindustrias)
-- ---------------------------------------------------------------------
CREATE TABLE proveedores (
  id_proveedor     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre           VARCHAR2(120) NOT NULL,
  tipo_proveedor   VARCHAR2(20)  NOT NULL,
  documento        VARCHAR2(20)  NOT NULL,
  contacto         VARCHAR2(100),
  telefono         VARCHAR2(20),
  direccion        VARCHAR2(200) NOT NULL,
  municipio        VARCHAR2(60)  NOT NULL,
  tipo_residuo     VARCHAR2(20)  NOT NULL,
  activo           CHAR(1)       DEFAULT 'S' NOT NULL,
  fecha_registro   DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_proveedores PRIMARY KEY (id_proveedor)
);

-- ---------------------------------------------------------------------
-- 4. PILAS_COMPOST: pilas donde se transforma el residuo
-- ---------------------------------------------------------------------
CREATE TABLE pilas_compost (
  id_pila          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  codigo           VARCHAR2(20)  NOT NULL,
  ubicacion        VARCHAR2(100),
  fecha_inicio     DATE          NOT NULL,
  fecha_fin        DATE,
  fase             VARCHAR2(20)  DEFAULT 'MESOFILICA' NOT NULL,
  capacidad_kg     NUMBER(10,2),
  observaciones    VARCHAR2(400),
  CONSTRAINT pk_pilas_compost PRIMARY KEY (id_pila)
);

-- ---------------------------------------------------------------------
-- 5. RECOLECCIONES: entradas de residuo (pesaje, fecha, origen, clasificación)
-- ---------------------------------------------------------------------
CREATE TABLE recolecciones (
  id_recoleccion     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_proveedor       NUMBER        NOT NULL,
  id_usuario         NUMBER        NOT NULL,
  id_pila            NUMBER,
  fecha_recoleccion  DATE          NOT NULL,
  peso_kg            NUMBER(10,2)  NOT NULL,
  tipo_residuo       VARCHAR2(20)  NOT NULL,
  clasificacion      VARCHAR2(20)  DEFAULT 'APTO' NOT NULL,
  observaciones      VARCHAR2(400),
  fecha_registro     DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_recolecciones PRIMARY KEY (id_recoleccion)
);

-- ---------------------------------------------------------------------
-- 6. MONITOREO_PILAS: seguimiento de temperatura, humedad, pH y volteos
-- ---------------------------------------------------------------------
CREATE TABLE monitoreo_pilas (
  id_monitoreo     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_pila          NUMBER        NOT NULL,
  id_usuario       NUMBER        NOT NULL,
  fecha_monitoreo  DATE          NOT NULL,
  temperatura      NUMBER(5,2)   NOT NULL,
  humedad          NUMBER(5,2)   NOT NULL,
  ph               NUMBER(4,2),
  volteo           CHAR(1)       DEFAULT 'N' NOT NULL,
  observaciones    VARCHAR2(400),
  CONSTRAINT pk_monitoreo_pilas PRIMARY KEY (id_monitoreo)
);

-- ---------------------------------------------------------------------
-- 7. LOTES_ABONO: abono/compost producido al finalizar una pila
-- ---------------------------------------------------------------------
CREATE TABLE lotes_abono (
  id_lote            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_pila            NUMBER        NOT NULL,
  codigo_lote        VARCHAR2(20)  NOT NULL,
  fecha_produccion   DATE          NOT NULL,
  kilos_producidos   NUMBER(10,2)  NOT NULL,
  calidad            VARCHAR2(20)  DEFAULT 'ESTANDAR' NOT NULL,
  estado             VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,
  observaciones      VARCHAR2(400),
  CONSTRAINT pk_lotes_abono PRIMARY KEY (id_lote)
);
